"""Phase 6C benchmark run: persistence, Baseline A and Baseline B under both splits and horizons.

    cd backend && python -m scripts.run_eval [--write-doc] [--allow-dirty]

Logs to the MLflow experiment "raceiq-tires" (tracking store: <repo>/mlruns, gitignored;
override with MLFLOW_TRACKING_URI): parameters, dataset hash, git SHA, FastF1 version, every
summary metric, the result tables, and three plots (error vs horizon step, error vs tyre age,
per-race MAE). Refuses to run on a dirty git tree unless --allow-dirty is given, so every
logged run is reproducible from its recorded git SHA + dataset hash.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
import warnings
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from app.config import settings  # noqa: E402
from app.tires.evaluation import EvalResult, evaluate  # noqa: E402
from app.tires.models.forecasting import PooledFixedEffects, StintLinearExtrapolation  # noqa: E402
from app.tires.models.persistence import PersistenceModel  # noqa: E402
from app.tires.report import latest_outputs  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
DOC = REPO / "docs" / "tire_eval_baselines.md"
START, END = "<!-- benchmarks:start -->", "<!-- benchmarks:end -->"
EXPERIMENT = "raceiq-tires"
LABEL = {"persistence": "Persistence (last 3 laps)", "stint_linear_extrapolation": "A · stint linear",
         "pooled_fixed_effects": "B · pooled fixed effects"}


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, check=False).stdout.strip()


def table(result: EvalResult, dataset_hash: str, sha: str, run_id: str | None) -> str:
    s = result.summary.sort_values(["split", "horizon", "mae"])
    lines = [f"Generated by `python -m scripts.run_eval --write-doc`: dataset `{dataset_hash[:12]}`, "
             f"git `{sha[:10]}`" + (f", MLflow run `{run_id}`" if run_id else "") + ".", "",
             "Lap-time forecast error in seconds; mean over races (± standard error across races). "
             "Bias = predicted − actual (> 0: forecasts too slow). Slope vs ref = mean |forecast slope − "
             "stint's ex-post OLS slope| on stints ≥ 15 laps (a reference, not ground truth).", "",
             "| Split | h | Model | Races | MAE | RMSE | Bias | 95% PI coverage | PI width | Slope vs ref (s/lap) |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in s.iterrows():
        cov = "—" if pd.isna(r["coverage"]) else f"{r['coverage']:.0%}"
        width = "—" if pd.isna(r["mean_width"]) else f"{r['mean_width']:.2f}"
        lines.append(f"| {r['split']} | {r['horizon']} | {LABEL[r['model']]} | {r['n_races']} | "
                     f"**{r['mae']:.3f}** ± {r['mae_se']:.3f} | {r['rmse']:.3f} | {r['bias']:+.3f} ± {r['bias_se']:.3f} | "
                     f"{cov} | {width} | {r['slope_mae_vs_ref']:.3f} |")
    lines += ["", "MAE by horizon step (LORO):", "", "| h | Model | " + " | ".join(f"step {i}" for i in range(1, 11)) + " |",
              "|---|---|" + "---|" * 10]
    st = result.by_step[result.by_step["split"] == "loro"]
    for (h, model), g in st.groupby(["horizon", "model"], sort=True):
        vals = {int(r.step): r.mae for r in g.itertuples()}
        lines.append(f"| {h} | {LABEL[model]} | " + " | ".join(f"{vals[i]:.3f}" if i in vals else "" for i in range(1, 11)) + " |")
    lines += ["", "MAE by compound (LORO, h = 5):", "", "| Model | SOFT | MEDIUM | HARD |", "|---|---|---|---|"]
    bc = result.by_compound[(result.by_compound["split"] == "loro") & (result.by_compound["horizon"] == 5)]
    for model, g in bc.groupby("model", sort=True):
        vals = {r.compound: f"{r.mae:.3f} ({r.n_races})" for r in g.itertuples()}
        lines.append(f"| {LABEL[model]} | {vals.get('SOFT', '—')} | {vals.get('MEDIUM', '—')} | {vals.get('HARD', '—')} |")
    lines += ["", "(Bracketed: number of races contributing to that compound.)"]
    return "\n".join(lines)


def plots(result: EvalResult, out: Path) -> list[Path]:
    paths = []
    colors = {"persistence": "#8a8683", "stint_linear_extrapolation": "#c98a2b", "pooled_fixed_effects": "#3b7dd8"}
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    for ax, h in zip(axes, (5, 10)):
        st = result.by_step[(result.by_step["split"] == "loro") & (result.by_step["horizon"] == h)]
        for model, g in st.groupby("model"):
            ax.plot(g["step"], g["mae"], marker="o", color=colors[str(model)], label=LABEL[str(model)])
        ax.set_title(f"MAE vs horizon step (LORO, h = {h})", fontsize=10)
        ax.set_xlabel("Steps ahead (laps)")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("MAE (s), mean over races")
    axes[0].legend(fontsize=8)
    fig.tight_layout()
    paths.append(out / "error_vs_horizon_step.png")
    fig.savefig(paths[-1], dpi=110)
    plt.close(fig)

    rec = result.records[(result.records["split"] == "loro") & (result.records["horizon"] == 5)].copy()
    rec["abs_err"] = (rec["pred"] - rec["actual"]).abs()
    rec["age_bin"] = (rec["tyre_age"] // 5) * 5
    fig, ax = plt.subplots(figsize=(7, 4))
    for model, g in rec.groupby("model"):
        per = g.groupby(["age_bin", "session_key"])["abs_err"].mean().groupby("age_bin").mean()
        ax.plot(per.index, per.values, marker="o", color=colors[str(model)], label=LABEL[str(model)])
    ax.set_xlabel("Tyre age of the forecast lap (5-lap bins)")
    ax.set_ylabel("MAE (s), mean over races")
    ax.set_title("Error vs tyre age (LORO, h = 5)", fontsize=10)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    paths.append(out / "error_vs_tyre_age.png")
    fig.savefig(paths[-1], dpi=110)
    plt.close(fig)

    br = result.by_race[(result.by_race["split"] == "loro") & (result.by_race["horizon"] == 5)]
    wide = br.pivot(index="session_key", columns="model", values="mae").sort_index()
    fig, ax = plt.subplots(figsize=(11, 4))
    width = 0.27
    for i, model in enumerate(wide.columns):
        ax.bar([x + (i - 1) * width for x in range(len(wide))], wide[model], width, color=colors[str(model)], label=LABEL[str(model)])
    ax.set_xticks(range(len(wide)), [k.replace("_R", "") for k in wide.index], rotation=60, fontsize=8)
    ax.set_ylabel("MAE (s)")
    ax.set_title("Per-race MAE (LORO, h = 5)", fontsize=10)
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    paths.append(out / "per_race_mae.png")
    fig.savefig(paths[-1], dpi=110)
    plt.close(fig)
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m scripts.run_eval")
    parser.add_argument("--data-dir", default=settings.data_dir)
    parser.add_argument("--hash", default=None, help="dataset hash prefix (default: newest)")
    parser.add_argument("--horizons", type=int, nargs="+", default=[5, 10])
    parser.add_argument("--min-train", type=int, default=8)
    parser.add_argument("--allow-dirty", action="store_true")
    parser.add_argument("--no-mlflow", action="store_true")
    parser.add_argument("--write-doc", action="store_true")
    args = parser.parse_args(argv)

    dirty = git("status", "--porcelain")
    if dirty and not args.allow_dirty:
        print("refusing to run: the git tree is dirty (commit first, or pass --allow-dirty):\n" + dirty, file=sys.stderr)
        return 2
    sha = git("rev-parse", "HEAD")
    frame, _log, meta = latest_outputs(Path(args.data_dir) / "tires", args.hash)
    models = [PersistenceModel(), StintLinearExtrapolation(), PooledFixedEffects()]
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        result = evaluate(frame, models, splits=("loro", "walk_forward"), horizons=tuple(args.horizons), min_train=args.min_train)

    run_id: str | None = None
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        figure_paths = plots(result, out)
        for name in ("summary", "by_step", "by_compound", "by_race"):
            getattr(result, name).to_csv(out / f"{name}.csv", index=False)
        if not args.no_mlflow:
            os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
            import mlflow

            mlflow.set_tracking_uri(os.environ.get("MLFLOW_TRACKING_URI", (REPO / "mlruns").as_uri()))
            mlflow.set_experiment(EXPERIMENT)
            with mlflow.start_run(run_name=f"benchmarks-{meta['hash'][:12]}") as run:
                run_id = run.info.run_id
                mlflow.log_params({"splits": "loro,walk_forward", "horizons": ",".join(map(str, args.horizons)),
                                   "min_train_races": args.min_train, "first_cut": 6, "cut_step": 2,
                                   "min_stint_laps": 12, "aggregation": "mean over races"})
                for model in models:
                    mlflow.log_params({f"{model.name}.{k}": v for k, v in model.params().items()})
                mlflow.set_tags({"dataset_hash": meta["hash"], "git_sha": sha, "git_dirty": str(bool(dirty)),
                                 "fastf1_version": ",".join(meta["fastf1_versions"]),
                                 "dataset_schema_version": str(meta["schema_version"]), "phase": "6C"})
                for r in result.summary.itertuples():
                    prefix = f"{r.model}.{r.split}.h{r.horizon}"
                    for metric in ("mae", "mae_se", "rmse", "bias", "bias_se", "coverage", "mean_width",
                                   "interval_score", "slope_mae_vs_ref"):
                        value = getattr(r, metric)
                        if pd.notna(value):
                            mlflow.log_metric(f"{prefix}.{metric}", float(value))
                for path in [*figure_paths, *out.glob("*.csv")]:
                    mlflow.log_artifact(str(path))
                text = table(result, meta["hash"], sha, run_id)
                (out / "benchmark_table.md").write_text(text, encoding="utf-8")
                mlflow.log_artifact(str(out / "benchmark_table.md"))
        text = table(result, meta["hash"], sha, run_id)
        print(text)
        if args.write_doc:
            fig_dir = REPO / "docs" / "figures" / "tires"
            fig_dir.mkdir(parents=True, exist_ok=True)
            for path in figure_paths:
                (fig_dir / f"eval_{path.name}").write_bytes(path.read_bytes())
            doc = DOC.read_text(encoding="utf-8")
            head, rest = doc.split(START, 1)
            DOC.write_text(f"{head}{START}\n{text}\n{END}{rest.split(END, 1)[1]}", encoding="utf-8")
            print(f"\nwrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
